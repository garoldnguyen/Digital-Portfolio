/* Self-hosts the Google Fonts the site uses (Cormorant, Josefin Sans, Lexend).
   Run it once with `node scripts/fonts.js` (needs internet); it needs nothing from npm.

   It asks Google for the same font families and weights as the old <link>, keeps only the subsets the pages need
   (latin, latin-ext, vietnamese: the name "Nguyễn" needs the Vietnamese one), downloads each distinct file into
   assets/fonts/ with a content hash in its name (so it can be cached for a year), and writes the @font-face rules
   into assets/css/golden-age.css between the FONTS markers. Weights map to the same files they did before, so the page
   looks exactly the same. All three families are licensed under the SIL Open Font License 1.1. */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const CSS_URL = 'https://fonts.googleapis.com/css2?family=Cormorant:wght@400;500;600&family=Josefin+Sans:wght@200;300;400;600&family=Lexend:wght@300;400;500&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';   // asks for woff2
const KEEP = new Set(['latin', 'latin-ext', 'vietnamese']);
const START = '/* ===== FONTS START (generated by scripts/fonts.js; do not edit by hand) ===== */';
const END = '/* ===== FONTS END ===== */';

async function get(url, asText) {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(url + ' -> HTTP ' + r.status);
  return asText ? r.text() : Buffer.from(await r.arrayBuffer());
}

(async () => {
  const css = await get(CSS_URL, true);
  const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].map(m => ({ subset: m[1], text: m[2] }));
  if (!blocks.length) throw new Error('no @font-face blocks found');
  const outDir = path.join(root, 'assets', 'fonts');
  fs.mkdirSync(outDir, { recursive: true });

  const byUrl = new Map();      // google url -> local file name
  const out = [];
  for (const b of blocks) {
    if (!KEEP.has(b.subset)) continue;
    const family = /font-family:\s*'([^']+)'/.exec(b.text)[1];
    const url = /url\((https:[^)]+)\)/.exec(b.text)[1];
    if (!byUrl.has(url)) {
      const buf = await get(url, false);
      const hash = crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8);
      const name = family.toLowerCase().replace(/\s+/g, '-') + '-' + b.subset + '-' + hash + '.woff2';
      fs.writeFileSync(path.join(outDir, name), buf);
      byUrl.set(url, name);
      console.log('saved', name, (buf.length / 1024).toFixed(1) + ' KB');
    }
    out.push(b.text.replace(/url\(https:[^)]+\)/, 'url(../fonts/' + byUrl.get(url) + ')').replace(/\s+/g, ' ').replace(/\{ /, '{').replace(/ \}/, '}') + '   /* ' + b.subset + ' */');
  }

  const block = START + '\n' + out.join('\n') + '\n' + END + '\n';
  const cssFile = path.join(root, 'assets', 'css', 'golden-age.css');
  let c = fs.readFileSync(cssFile, 'utf8').replace(/\r\n/g, '\n');
  const a = c.indexOf(START), z = c.indexOf(END);
  c = (a >= 0 && z > a) ? c.slice(0, a) + block + c.slice(z + END.length + 1) : block + c;
  fs.writeFileSync(cssFile, c);

  fs.writeFileSync(path.join(outDir, 'README.txt'),
    'Cormorant, Josefin Sans and Lexend, copied from Google Fonts (https://fonts.google.com) so the site does not load anything from Google.\n' +
    'All three are licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).\n' +
    'Regenerate with: node scripts/fonts.js\n');
  console.log('\n' + byUrl.size + ' font files, ' + out.length + ' @font-face rules written to assets/css/golden-age.css');
})().catch(e => { console.error('FAILED:', e.message); process.exit(1); });
